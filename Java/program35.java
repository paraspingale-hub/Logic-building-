class Program35
{
    public static void Display()
    {
        int iCnt = 0;

        iCnt = 5;

        while(iCnt >= 1)
        {
            System.out.print(iCnt);
            iCnt--;
        }

        System.out.println();
    }

    public static void main(String A[])
    {
        Display();
    }
}