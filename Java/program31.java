class Program30
{
    public static void Display()
    {
        int iCnt = 0;

        iCnt = 1;

        while(iCnt <= 5)
        {
            System.out.print(" * ");
            iCnt++;
        }

        System.out.println();
    }

    public static void main(String A[])
    {
        Display();
    }
}